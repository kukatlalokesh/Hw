import numpy as np

first_array = np.array([10, 20, 30, 40])
second_array = np.array([2, 4, 5, 8])

print("First Array:", first_array)
print("Second Array:", second_array)

print("\nAddition:")
print(first_array + second_array)

print("\nSubtraction:")
print(first_array - second_array)

print("\nMultiplication:")
print(first_array * second_array)

print("\nDivision:")
print(first_array / second_array)
